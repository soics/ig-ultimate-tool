"""Build src/ig_ultimate/data/words.txt: real words from many languages for the username finder.

Not run by the app. To rebuild (needs `pip install wordfreq` in a separate environment):
  1. python -c "import wordfreq; ..."  dump `lang<TAB>rank<TAB>word` for each language in LANGS,
     from wordfreq.top_n_list(lang, 25000, wordlist="best"), into raw.tsv
  2. download the LDNOOBW bad-word lists (one file per language code) into a folder
  3. python scripts/build_words.py raw.tsv <bad-word folder> > src/ig_ultimate/data/words.txt

Per language it skips the SKIP most common words (taken long ago, and mostly little words like
"the"), then keeps the next CAP words that make a clean username.
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

from ig_ultimate import names

SKIP, CAP = 1000, 3000
LANGS = "ca cs da de en es fi fil fr hu id is it lt lv ms nb nl pl pt ro sh sk sl sv tr".split()
HEADER = """\
# Real words for the username finder, by language. Generated by scripts/build_words.py; do not edit.
# Source: wordfreq 3.1.1 word frequency lists. Robyn Speer. (2022). rspeer/wordfreq: v3.0 (v3.0.2).
# Zenodo. https://doi.org/10.5281/zenodo.7199437
# License of THIS FILE: Creative Commons Attribution-ShareAlike 4.0 (CC BY-SA 4.0),
# https://creativecommons.org/licenses/by-sa/4.0/ (the rest of IG Ultimate Tool is MIT).
# Changes: lowercased, accents removed, filtered to clean usernames, the most common words dropped.
# Bad words were removed using the LDNOOBW lists (CC BY 4.0); those lists are not included.
"""


# Languages LDNOOBW has no list for (sh ro sk sl lt lv is id ms ca): the common vulgar words by hand.
EXTRA_BAD = """kurac kurca kurcu jebem jebati jebiga jebo jebote jebem jebac jebena jebeni picka pizda pizde
pizdu govno sranje kurva kurve kurvo kurvin peder pederi drolja guzica pickin pula pulii muie futut
futu fute muist curva curvo kokot kokoti pica pici kurvy drek fukati fukam bybis pyzda sudas mauka
dirsa kunta typpi rassgat hora kontol memek ngentot bangsat jancok pukimak puki pantat lancau
butoh collons cony fotre fotut putes""".split()


def load_bad(folder: Path) -> tuple[set[str], tuple[str, ...]]:
    exact = set(EXTRA_BAD)
    for f in folder.glob("*.txt"):
        for line in f.read_text(encoding="utf-8").splitlines():
            w = line.strip()
            if w and " " not in w:
                exact.add(names.normalize(w))
    exact.discard("")
    return exact, tuple(w for w in exact if len(w) >= 5)  # long ones also count inside a word


def clean(word: str, bad: set[str], bad_parts: tuple[str, ...]) -> str:
    """The username form of a word, or "" if it doesn't make a clean one."""
    if not word.isalpha():  # digits, apostrophes, hyphens: not a plain word
        return ""
    n = names.normalize(word)
    if not (n.isascii() and n.isalpha() and 3 <= len(n) <= 8):
        return ""
    if names.validate(n)[0] != "ok" or names.risks(n) or names._pronounce(n) < 40:
        return ""
    if n in bad or any(p in n for p in bad_parts):
        return ""
    return n


def build(raw: Path, bad_dir: Path) -> str:
    bad, bad_parts = load_bad(bad_dir)
    curated = names.curated()
    picked: dict[str, list[str]] = defaultdict(list)
    seen: set[str] = set(curated)
    for line in raw.read_text(encoding="utf-8").splitlines():
        lang, rank, word = line.split("\t")
        if lang not in LANGS or int(rank) <= SKIP or len(picked[lang]) >= CAP:
            continue
        n = clean(word, bad, bad_parts)
        if n and n not in seen:  # first language wins; hand-picked words keep their own entry
            seen.add(n)
            picked[lang].append(n)
    out = [HEADER]
    for lang in LANGS:
        out.append(f"## lang={lang}")
        row: list[str] = []
        for n in picked[lang]:
            if sum(len(x) + 1 for x in row) + len(n) > 99:
                out.append(" ".join(row))
                row = []
            row.append(n)
        if row:
            out.append(" ".join(row))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(build(Path(sys.argv[1]), Path(sys.argv[2])))
