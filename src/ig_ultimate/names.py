CONFUSING = ("rn", "vv", "cl", "nn", "ii", "ll1", "0o", "o0", "1l", "l1", "il1")


@lru_cache(maxsize=100_000)
def _pronounce(name: str) -> int:
    s = re.sub(r"[^a-z]", "", name)
    if not s:
        return 0
    marks = "".join("v" if c in "aeiouy" else "c" for c in s)
    if "v" not in marks:
        return 25 if len(s) <= 2 else 10
    score = 80
    run_c = max(map(len, re.findall("c+", marks)), default=0)
    run_v = max(map(len, re.findall("v+", marks)), default=0)
    if run_c == 3:
        clusters = {s[m.start() : m.end()] for m in re.finditer("ccc", marks)}
        score -= 15 if clusters <= GOOD3 else 35
    elif run_c >= 4:
        score -= 55
    score -= {3: 15}.get(run_v, 35 if run_v >= 4 else 0)
    if len(s) >= 2 and marks[:2] == "cc" and s[:2] not in ONSET2:
        score -= 20
    switches = sum(a != b for a, b in itertools.pairwise(marks))
    score += round(15 * switches / max(1, len(s) - 1))
    if any(c.isdigit() for c in name):
        score -= 20
    return max(0, min(100, score))


def components(name: str) -> dict[str, int]:
    e = lexicon().get(name)
    n, digits = len(name), sum(c.isdigit() for c in name)
    punct = name.count(".") + name.count("_")
    confusing = sum(p in name for p in CONFUSING) + (("l" in name or "i" in name) and "1" in name)
    pron = _pronounce(name)
    r = risks(name)
    palindrome = n >= 3 and name == name[::-1]

    visual = 100 - min(36, 12 * digits) - 30 * name.count(".") - 25 * name.count("_") - 25 * confusing
    visual -= 15 * bool(re.search(r"(.)\1\1", name)) + 10 * bool(re.search(r"[a-z]\d+[a-z]", name))
    visual += 5 * palindrome
    memorable = 40 + (30 if n <= 4 else 20 if n <= 6 else 10 if n <= 8 else 0) + (20 if e else 0)
    memorable += round(pron * 0.2) - 8 * digits - 15 * punct + 5 * palindrome
    if e:
        meaning = {"c": 72, "u": 82, "r": 88}[e["tier"]] + 6 * bool(e["senses"])
        meaning += 4 * bool({"luxury", "dark", "rare"} & set(e["cats"]))
        meaning -= 4 * (len(e["langs"]) > 1 or bool(e["note"]))
        rarity = {"c": 45, "u": 70, "r": 90}[e["tier"]]
    else:
        meaning = 35 if pron >= 70 and not digits else 15 if digits else 10
        rare_letters = min(24, 8 * sum(c in "jqxzkv" for c in name)) if n <= 3 else 0
        rarity = 50 + rare_letters + (20 if n <= 2 else 0)
    clarity = 100 - (0 if e else 10) - 10 * digits - 20 * punct - 25 * confusing
    clarity -= 0 if e else 8 * bool(re.search(r"([a-z])\1", name)) + 8 * bool(re.search(r"q(?!u)", name))
    return {
        "length": 0,  # filled in per profile (it depends on the curve)
        "visual": visual,
        "pronounce": pron,
        "memorable": memorable,
        "meaning": meaning,
        "rarity": rarity,
        "clarity": clarity,
        "culture": 0 if "offensive" in r else 35 if "sensitive" in r else 100,
        "brand": 0 if "impersonation" in r else 35 if "brand" in r else 100,
    }


def score(name: str, profile: str = "balanced") -> int:
    return explain(name, profile)["score"]


def explain(name: str, profile: str = "balanced") -> dict:
    """Deterministic 0-100 score with its breakdown. Same name + profile = same score, always."""
    weights, curve = PROFILES.get(profile, PROFILES["balanced"])
    parts = components(name)
    c = CURVES[curve]
    parts["length"] = c.get(len(name), max(20, min(c.values()) - 10 * (len(name) - max(c))))
    parts = {k: max(0, min(100, v)) for k, v in parts.items()}
    total = sum(w * parts[k] for k, w in zip(COMPONENTS, weights, strict=True)) / sum(weights)
    r = risks(name)
    if "offensive" in r:
        total = 0
    elif "impersonation" in r:
        total = min(total, 5)
    elif "brand" in r:
        total *= 0.8
    if len(name) >= 4 and parts["pronounce"] < 40:
        total *= 0.75  # a 4+ letter name nobody can say is not OG, however short
    if validate(name)[0] == "invalid":
        total = 0
    return {
        "name": name,
        "profile": profile,
        "score": round(total),
        "parts": [
            {"part": k, "value": parts[k], "weight": w} for k, w in zip(COMPONENTS, weights, strict=True)
        ],
        "risks": r,
        "note": "A quality score only. It says nothing about whether the name is free, or worth money.",
    }


def blocked(name: str) -> bool:
    """Never queued for automatic claiming: offensive or impersonation-looking names, invalid names."""
    r = risks(name)
    return "offensive" in r or "impersonation" in r or validate(name)[0] == "invalid"
