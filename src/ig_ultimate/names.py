# ------------------------------------------------------------------ validation

NAME = re.compile(r"[a-z0-9._]{1,30}")
_FOLD = str.maketrans({"ß": "ss", "æ": "ae", "ø": "o", "œ": "oe", "ł": "l", "đ": "d", "þ": "th", "ð": "d"})


def normalize(raw: str) -> str:
    """The username form of a word: lowercase, accents removed (élan -> elan), spaces and dashes dropped."""
    text = unicodedata.normalize("NFKD", str(raw).strip().lstrip("@").lower().translate(_FOLD))
    return "".join(c for c in text if not unicodedata.combining(c) and c not in " -'")


def validate(name: str) -> tuple[str, str]:
    """("ok" | "unverified" | "invalid", why). Rules are Instagram's documented character set plus the
    widely reported period rules; "unverified" means only Instagram itself can say (the claim does)."""
    if not NAME.fullmatch(name):
        return "invalid", "Only a-z, 0-9, periods and underscores, 1 to 30 characters."
    if name.startswith(".") or name.endswith(".") or ".." in name:
        return "invalid", "A username can't start or end with a period or have two in a row."
    if name.isdigit():
        return "unverified", "Numbers only: Instagram may refuse it."
    if len(name) <= 2:
        return "unverified", "1-2 characters: Instagram may not allow it any more."
    return "ok", ""


