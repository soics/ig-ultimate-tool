SENSITIVE = {"isis": "Also the name of a terrorist group: easily misread."}


@lru_cache(maxsize=100_000)  # called several times per name while scoring
def risks(name: str) -> dict[str, str]:
    letters = re.sub(r"[^a-z]", "", name)
    out = {}
    if letters in OFFENSIVE_EXACT or any(p in letters for p in OFFENSIVE_PARTS):
        out["offensive"] = "Offensive or adult word."
    if letters in IMPERSONATION or any(w in letters for w in ("instagram", "official", "admin", "support")):
        out["impersonation"] = "Looks like an official or staff account."
    elif letters in BRANDS:
        out["brand"] = "A well-known brand name: high impersonation and trademark risk."
    if letters in SENSITIVE:
        out["sensitive"] = SENSITIVE[letters]
    return out


# ------------------------------------------------------------------ lexicon


@cache
def lexicon() -> dict[str, dict]:
    """name -> {cats, tier, langs, senses: [{lang, meaning, original}], note}, duplicates merged."""
    text = resources.files("ig_ultimate").joinpath("data", "lexicon.txt").read_text(encoding="utf-8")
    out: dict[str, dict] = {}
    cats, tier, lang = (), "c", "en"
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("##"):
            opts = dict(kv.split("=", 1) for kv in line[2:].split())
            cats, tier, lang = tuple(opts["cats"].split(",")), opts["tier"], opts["lang"]
            continue
        if not line or line.startswith("#"):
            continue
        rows = [line.split("|")] if "|" in line else [[w] for w in line.split()]
        for parts in rows:
            word, meaning, original, note = (*(p.strip() for p in parts), "", "", "")[:4]
            name = normalize(word)
            if validate(name)[0] == "invalid":
                continue
            e = out.setdefault(name, {"cats": [], "tier": tier, "langs": [], "senses": [], "note": ""})
            e["cats"] += [c for c in cats if c not in e["cats"]]
            e["tier"] = max(e["tier"], tier, key="cur".index)  # the rarer label wins
            if lang not in e["langs"]:
                e["langs"].append(lang)
            if meaning and all(s["meaning"] != meaning for s in e["senses"]):
                e["senses"].append({"lang": lang, "meaning": meaning, "original": original})
            if note and note not in e["note"]:
                e["note"] = f"{e['note']} {note}".strip()
    return out


def describe(name: str) -> dict:
    """Provenance for one name: where it came from, what it means, and how sure we are."""
    e = lexicon().get(name)
    kind, why = validate(name)
    info = {"eligibility": kind, "eligibility_note": why, "risks": risks(name)}
    if not e:
        return {**GENERATED, **info}
    meanings = {s["meaning"] for s in e["senses"]}
    ambiguous = len(meanings) > 1 or len(e["langs"]) > 1 or bool(e["note"])
    return {
        **SOURCE,
        **info,
        "langs": e["langs"],
        "senses": e["senses"],
        "note": e["note"],
        "tier": e["tier"],
        "confidence": "high",  # every entry is a standard dictionary sense; unsure ones were left out
        "ambiguous": ambiguous,
    }


# ------------------------------------------------------------------ generators
# Each yields (name, category). Small spaces are generated whole; the invented space is open-ended
# and is pulled in bounded batches by the store.


def _tags(name: str, category: str) -> list[str]:
    e = lexicon().get(name)
    tags = [category, *(e["cats"] if e else [])]
    if len(name) <= 3 and name.isalnum():
        tags.append("ultra")
    tags += [f"lang:{x}" for x in (e["langs"] if e else []) if x != "en"]
    return list(dict.fromkeys(tags))


def from_lexicon(category: str) -> Iterator[str]:
    yield from (n for n, e in lexicon().items() if category in e["cats"])


def _shuffled(items, seed: str) -> list[str]:
    """Same order every run, but not a-b-c (equal scores are tried in this order)."""
    out = list(items)
    random.Random(seed).shuffle(out)
    return out


def ultra() -> Iterator[str]:
    """3 characters starting with a letter: letters only first, then with digits."""
    letters, both = string.ascii_lowercase, string.ascii_lowercase + string.digits
    for mixed in (False, True):
        combos = ("".join(t) for t in itertools.product(letters, both, both))
        yield from _shuffled((x for x in combos if (not x.isalpha()) == mixed), f"ultra-3-{mixed}")


def alnum() -> Iterator[str]:
    """Letters and numbers on purpose: x77, ok7, k9x, zen7. No random strings."""
    L, D = string.ascii_lowercase, string.digits
    yield from _shuffled((a + d + d for a in L for d in D), "alnum-2")
    yield from _shuffled((a + b + d for a in L for b in L for d in D), "alnum-3")
    yield from _shuffled((a + d + b for a in L for d in D for b in L), "alnum-4")
    words3 = [n for n, e in lexicon().items() if len(n) == 3 and n.isalpha() and "short" in e["cats"]]
    yield from _shuffled((w + d for w in words3 for d in D), "alnum-5")


ONSETS = "b d f g h k l m n p r s t v z br dr fr gr kr pr tr vr st sk sl".split()
LATER = "b d f k l m n r s t v z".split()  # clusters only at the start keep names easy to say
VOWELS = "a e i o u".split()
CODAS = "n r l s x".split()


def invented(start: int = 0) -> Iterator[tuple[int, str]]:
    """(cursor, name) of pronounceable made-up names, the same sequence every run (so it can resume).
    Only names that read like a real word survive: no dictionary words, nothing hard to say."""
    words = lexicon()
    for i in itertools.count(start):
        rng = random.Random(f"ig-ultimate-invented-{i}")
        first = rng.choice(ONSETS) + rng.choice(VOWELS)
        syl = lambda r=rng: r.choice(LATER) + r.choice(VOWELS)  # noqa: E731
        shape = rng.randrange(5)
        if shape == 0:
            name = first + syl()  # kazo
        elif shape == 1:
            name = first + syl() + rng.choice(CODAS)  # velan
        elif shape == 2:
            name = rng.choice(VOWELS) + syl() + rng.choice(["", *CODAS])  # avor
        elif shape == 3:
            name = first + rng.choice(CODAS[:4]) + syl()  # kirva
        else:
            name = first + syl() + syl()  # temora
        parts = re.findall(r"[^aeiou]*[aeiou]", name)
        if (
            name in words
            or len(set(parts)) < len(parts)  # no kaka
            or re.search(r"(.)\1", name)
            or not 3 <= len(name) <= 7
            or risks(name)
            or _pronounce(name) < 85
        ):
            continue
        yield i, name


FOUR_V = "aeiou"
FOUR_C = "".join(c for c in string.ascii_lowercase if c not in FOUR_V)


@cache
def _four_patterns() -> list[str]:
    """The 16 consonant/vowel shapes of a 4-letter name, easiest to say first (baba before bbbb)."""
    shapes = ["".join(p) for p in itertools.product("cv", repeat=4)]
    sample = lambda s: "".join("b" if x == "c" else "a" for x in s)  # noqa: E731
    return sorted(shapes, key=lambda s: (-_pronounce(sample(s)), s))


def four(start: int = 0) -> Iterator[tuple[int, str]]:
    """(cursor, name) of all 456,976 four-letter names, the same order every run so it can resume:
    shape by shape (easiest to say first), shuffled inside each shape."""
    i = 0
    for shape in _four_patterns():
        size = 1
        for x in shape:
            size *= len(FOUR_V if x == "v" else FOUR_C)
        if i + size <= start:  # whole shape already handed out: skip it without building it
            i += size
            continue
        pools = [FOUR_V if x == "v" else FOUR_C for x in shape]
        for name in _shuffled(("".join(t) for t in itertools.product(*pools)), f"four-{shape}"):
            if i >= start:
                yield i, name
            i += 1


def generate(category: str) -> Iterator[str]:
    """Every candidate of a finite category (not invented / four / custom)."""
    if category == "words":  # every real word of 4+ letters, from every list
        yield from (n for n in lexicon() if len(n) >= 4 and n.isalpha())
    elif category == "words3":
        yield from (n for n in lexicon() if len(n) == 3 and n.isalpha())
    elif category == "ultra":
        yield from (n for n in lexicon() if len(n) == 3)
        yield from ultra()
    elif category == "alnum":
        yield from alnum()
    else:
        yield from from_lexicon(category)


